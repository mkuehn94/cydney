import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

test.use({ baseURL: 'http://127.0.0.1:5176' })

async function ready(page: Page, path = '/') {
  const created = page.waitForResponse(r => r.url().endsWith('/api/device/sessions') && r.request().method() === 'POST')
  await page.goto(path === '/' ? '/?preview=1' : path)
  const session = await (await created).json()
  await expect(page.locator('.device-screen img')).toBeVisible()
  await expect(page.locator('.keyboard-controls button').first()).toBeEnabled()
  return session
}

test('cameras page', async ({ page }) => {
  const created = await ready(page)
  expect(created.center).toEqual([11.5099957, 48.1816035])
  expect(created.home).toEqual(created.center)
  expect(created.zoom).toBe(18)
  const opened = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.getByRole('button', { name: /^cameras/i }).click()
  expect((await (await opened).json()).page).toBe('cameras')
  await expect(page.locator('.keyboard-controls button').first()).toBeEnabled()
  const state = await (await page.request.get(`/api/device/${created.id}/state`)).json()
  expect(state.camera_directory).toEqual([])
  expect(state.camera_view).toBeNull()
  await expect(page.locator('.camera-image-link')).toHaveCount(0)
  await page.getByTestId('device-screen').focus()
  let action = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.keyboard.press('Escape')
  expect((await (await action).json()).page).toBe('map')
  await expect(page.locator('.keyboard-controls button').first()).toBeEnabled()
  action = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.keyboard.press('v')
  expect((await (await action).json()).page).toBe('cameras')
})

test('start position from url', async ({ page }) => {
  const session = await ready(page, '/?lat=53.5511&lon=9.9937&zoom=14')
  expect(session.center).toEqual([9.9937, 53.5511])
  expect(session.home).toEqual([11.5099957, 48.1816035])
  expect(session.mode).toBe('live')
  expect(session.observations).toBe(0) // feeds are off in the test server
  expect(session.fleet.in_view.scooters).toBe(0)
  expect(session.fleet.in_view.bikes).toBe(0)
  await expect(page.getByLabel('Available shared vehicles')).toContainText('0 scooters, 0 bikes on screen')
  await expect(page.getByRole('heading', { name: 'Sources' })).toBeVisible()
  await expect(page.getByLabel('Latitude', { exact: true })).toHaveValue('53.5511')
  await expect(page.getByLabel('Longitude', { exact: true })).toHaveValue('9.9937')
})

test('pan and zoom', async ({ page }) => {
  const created = await ready(page, '/?lat=53.5511&lon=9.9937&zoom=14')
  await page.getByTestId('device-screen').focus()
  let action = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.keyboard.press('ArrowRight')
  const panned = await (await action).json()
  expect(panned.center).not.toEqual(created.center)
  expect(panned.viewport.id).toBe(created.viewport.id)
  expect(panned.home).toEqual(created.home)
  await expect(page.locator('.keyboard-controls button').first()).toBeEnabled()
  action = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.keyboard.press('-')
  const zoomed = await (await action).json()
  expect(zoomed.zoom).toBe(13)
  expect(zoomed.viewport.detail).toBe('overview')
  expect(zoomed.viewport.bounds).not.toEqual(panned.viewport.bounds)
  const manifest = await (await page.request.get(`/api/sources?device=${created.id}`)).json()
  expect(manifest.viewport.id).toBe(zoomed.viewport.id)
  expect(zoomed.observations).toBe(0)
})

test('coordinate form', async ({ page }) => {
  await ready(page)
  await page.getByLabel('Latitude', { exact: true }).fill('53.5511')
  await page.getByLabel('Longitude', { exact: true }).fill('9.9937')
  const action = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.getByRole('button', { name: 'Go', exact: true }).click()
  const result = await (await action).json()
  expect(result.center).toEqual([9.9937, 53.5511])
  expect(result.zoom).toBe(18)
  await expect(page.getByRole('link', { name: /frame only/ })).toHaveAttribute('href', /lat=53\.5511&lon=9\.9937&zoom=18/)
})

test('browser location', async ({ page, context }) => {
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: 48.15, longitude: 11.59, accuracy: 24 })
  const created = await ready(page)
  let position = page.waitForResponse(r => r.url().endsWith('/position'))
  await page.getByRole('button', { name: 'Use my location', exact: true }).click()
  const fixed = await (await position).json()
  expect(fixed.center).toEqual([11.59, 48.15])
  expect(fixed.home).toEqual(created.home)
  expect(fixed.location).toMatchObject({ accuracy_m: 24, fresh: true, mode: 'follow' })
  await expect(page.getByLabel('Location status')).toContainText('±24m')
  await expect(page.getByRole('button', { name: 'Browse map', exact: true })).toBeEnabled()
  await page.getByTestId('device-screen').focus()
  const action = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/action'))
  await page.keyboard.press('ArrowRight')
  const panned = await (await action).json()
  expect(panned.location.mode).toBe('browse')
  await expect(page.getByRole('button', { name: 'Follow location', exact: true })).toBeEnabled()
  position = page.waitForResponse(r => r.url().endsWith('/position'))
  await context.setGeolocation({ latitude: 48.151, longitude: 11.591, accuracy: 12 })
  const updated = await (await position).json()
  expect(updated.location.position).toEqual([11.591, 48.151])
  expect(updated.center).toEqual(panned.center)
  await expect(page.getByLabel('Location status')).toContainText('±12m')
  await page.getByRole('button', { name: 'Follow location', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Browse map', exact: true })).toBeEnabled()
  await expect(page.locator('.location-controls small').filter({ hasText: /^Camera / })).toContainText('48.15100, 11.59100')
})
